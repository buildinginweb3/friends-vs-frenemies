for (const [k, v] of Object.entries(ABILITY_GLYPHS)) PIXEL_ICONS[k] = v;

/** Resolve glyph rows for any icon id (fallback: rarity diamond). */
export function iconRows(id: string): readonly string[] {
  return PIXEL_ICONS[id] ?? PIXEL_ICONS.rarity;
}

/** Icon accent colors by id (single-language palette). */
export function iconColor(id: string): string {
  if (id.startsWith("ab-")) return "#7a5fc0";
  if (id === "rf" || id === "prod" || id === "economy") return "#7db83e";
  if (id === "hp" || id === "vitality" || id === "regen" || id === "mend") return "#d95f4b";
  if (id === "boss" || id === "dmg" || id === "power" || id === "explosive" || id === "burn") return "#c96a2e";
  if (id === "crit" || id === "rarity" || id === "upgrade") return "#e8c53a";
  if (id === "armor" || id === "defense" || id === "bulwark" || id === "barrier") return "#3f7fbf";
  if (id === "rate" || id === "rapid" || id === "move" || id === "quick" || id === "boots") return "#8fd6c2";
  return "#141414";
}

/** Canvas pixel-icon draw: hard rects, no smoothing, pixel grid. */
export function drawPixelIcon(
  ctx: CanvasRenderingContext2D, id: string, cx: number, cy: number, scale = 2,
): void {
  const rows = iconRows(id);
  const col = iconColor(id);
  const w = rows[0].length, h = rows.length;
  const ox = Math.round(cx - (w * scale) / 2), oy = Math.round(cy - (h * scale) / 2);
  ctx.save();
  ctx.imageSmoothingEnabled = false;
  for (let y = 0; y < h; y++) {
    const row = rows[y];
    for (let x = 0; x < row.length; x++) {
      const c = row[x];
      if (c === ".") continue;
      ctx.fillStyle = c === "o" ? col : "#141414";
      ctx.fillRect(ox + x * scale, oy + y * scale, scale, scale);
    }
  }
  ctx.restore();
}

/** Strip decorative glyphs from boss/plate names (root cause: UI wrapping
 * clean names with star/diamond/warning/box glyphs that headless fonts miss). */
export function cleanName(name: string): string {
  return name
    .replace(/[◇◆★☆♥❤⚠⚒✦■□●○▶◀▲▼♦♢✚✖✔✓×►◄]/g, "")
    .replace(/\s{2,}/g, " ")
    .trim();
}
